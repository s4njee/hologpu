import { basicParticleEffect, renderParams, randomInit } from '../_particles/basic.ts';
const params = {
  ...renderParams,
  count: { ...renderParams.count, default: 65536 },
  system: {
    type: 'enum',
    default: 'lorenz',
    options: ['lorenz', 'aizawa', 'clifford', 'dejong'],
    group: 'Attractor',
    description: 'Differential Lorenz/Aizawa or iterated Clifford/De Jong system.',
  },
  rate: {
    type: 'f32',
    default: 0.6,
    min: 0.05,
    max: 2,
    step: 0.05,
    group: 'Attractor',
    description: 'Differential-system simulation rate; maps take one iteration per fixed tick.',
  },
  a: {
    type: 'f32',
    default: -1.4,
    min: -3,
    max: 3,
    step: 0.05,
    group: 'Attractor',
    description:
      'First map coefficient; Lorenz sigma and Aizawa coefficients retain canonical values.',
  },
  b: {
    type: 'f32',
    default: 1.6,
    min: -3,
    max: 3,
    step: 0.05,
    group: 'Attractor',
    description: 'Second map coefficient.',
  },
  c: {
    type: 'f32',
    default: 1,
    min: -3,
    max: 3,
    step: 0.05,
    group: 'Attractor',
    description: 'Third map coefficient.',
  },
  d: {
    type: 'f32',
    default: 0.7,
    min: -3,
    max: 3,
    step: 0.05,
    group: 'Attractor',
    description: 'Fourth map coefficient.',
  },
  rotation: {
    type: 'f32',
    default: 0.25,
    min: -3.14,
    max: 3.14,
    step: 0.05,
    group: 'View',
    description: 'Rotation of the projected three-dimensional attractor.',
  },
} as const;
export default basicParticleEffect(
  {
    id: 'attractors',
    title: 'Four additive HDR attractors',
    family: 'particles',
    core: true,
    tags: ['lorenz', 'aizawa', 'clifford', 'dejong', 'hdr'],
    params,
    inputs: [],
    features: [],
    presets: {
      aizawa: { system: 'aizawa', rate: 1, trail: 0.98, tint: '#f5b785' },
      dejong: {
        system: 'dejong',
        a: 1.4,
        b: -2.3,
        c: 2.4,
        d: -2.1,
        trail: 0.99,
        exposure: 0.5,
        tint: '#a1b6f1',
      },
    },
    quality: { resolutionScale: [0.25, 1] },
    reducedMotion: { time: 0 },
    fallback: 'radial-gradient(ellipse,#a1b6f1,#07111e)',
  },
  {
    initialize: `${randomInit}if(params.system==0u){p.position=vec4f(p.position.xyz*2+vec3f(0,0,24),p.position.w);}else if(params.system==1u){p.position=vec4f(p.position.xyz*.2+vec3f(.1,0,0),p.position.w);}`,
    extra: `fn derivative(v:vec3f)->vec3f{if(params.system==0u){return vec3f(10*(v.y-v.x),v.x*(28-v.z)-v.y,v.x*v.y-(8.0/3.0)*v.z);}let r=v.x*v.x+v.y*v.y;return vec3f((v.z-.7)*v.x-3.5*v.y,3.5*v.x+(v.z-.7)*v.y,.6+.95*v.z-v.z*v.z*v.z/3-r*(1+.25*v.z)+.1*v.z*v.x*v.x*v.x);}`,
    step: `if(params.system<2u){let dt=frame.delta*params.rate;let v=p.position.xyz;let k1=derivative(v);let k2=derivative(v+k1*dt*.5);let k3=derivative(v+k2*dt*.5);let k4=derivative(v+k3*dt);var q=v+dt*(k1+2*k2+2*k3+k4)/6;if(!all(abs(q)<=vec3f(100))){q=vec3f(.1,.1,select(0.0,24.0,params.system==0u));}p.position=vec4f(q,p.position.w);}else {let v=p.position.xy;var q=vec2f(sin(params.a*v.y)+params.c*cos(params.a*v.x),sin(params.b*v.x)+params.d*cos(params.b*v.y));if(params.system==3u){q=vec2f(sin(params.a*v.y)-cos(params.b*v.x),sin(params.c*v.x)-cos(params.d*v.y));}p.position=vec4f(q,0,p.position.w);}`,
    position: `select(select(vec2f((cos(params.rotation)*p.position.x+sin(params.rotation)*p.position.y)/24,(p.position.z-24)/28),vec2f(cos(params.rotation)*p.position.x+sin(params.rotation)*p.position.y,p.position.z-.5)*.7,params.system==1u),p.position.xy*.38,params.system>=2u)`,
  },
);
