// Generates the per-effect exports, lazy loader and catalogue.json from `packages/effects/src`.
//
// This used to run on `predev`/`prebuild`/`pretypecheck`, which rewrote committed package.json
// files on every run. Now it is a plain generator: run `pnpm catalogue` after adding an effect,
// commit the result, and CI runs `pnpm catalogue:check` to fail if the committed output is stale
// (M4 story 4.2).
//
//   node scripts/catalogue.mjs          # write
//   node scripts/catalogue.mjs --check  # fail if the committed output differs
import { format } from 'prettier';
import ts from 'typescript';
import { existsSync, readFileSync } from 'node:fs';
import { readdir, writeFile } from 'node:fs/promises';

const check = process.argv.includes('--check');
const ids = (await readdir('packages/effects/src', { withFileTypes: true }))
  .filter((d) => d.isDirectory() && !d.name.startsWith('_'))
  .map((d) => d.name)
  .sort();

/** path -> exact file contents the generator would produce. */
const outputs = new Map();
const plain = (path, text) => outputs.set(path, text);
const formatted = async (path, text) =>
  outputs.set(
    path,
    await format(text, { parser: 'typescript', singleQuote: true, printWidth: 100 }),
  );

const imports = ids.map((id, i) => `import effect${i} from './${id}/index.ts';`).join('\n');
await formatted(
  'packages/effects/src/index.ts',
  `// Generated by scripts/catalogue.mjs. Add an effect directory to extend the browser.\nimport type { EffectDefinition } from '@mk7s/hologpu-core';\n${imports}\nexport const catalogue = [${ids.map((_id, i) => `effect${i}`).join(', ')}] as unknown as readonly EffectDefinition[];\n`,
);

const p = JSON.parse(readFileSync('packages/hologpu/package.json', 'utf8'));
const e = JSON.parse(readFileSync('packages/effects/package.json', 'utf8'));
p.exports['./effects'] = {
  source: './src/effects.ts',
  types: './dist/effects.d.ts',
  import: './dist/effects.js',
};
for (const id of ids) {
  p.exports[`./effects/${id}`] = {
    source: `./src/effects/${id}.ts`,
    types: `./dist/effects/${id}.d.ts`,
    import: `./dist/effects/${id}.js`,
  };
  e.exports[`./${id}`] = {
    source: `./src/${id}/index.ts`,
    types: `./dist/${id}/index.d.ts`,
    import: `./dist/${id}/index.js`,
  };
  plain(
    `packages/hologpu/src/effects/${id}.ts`,
    `export { default } from '@mk7s/hologpu-effects/${id}';\nexport * from '@mk7s/hologpu-effects/${id}';\n`,
  );
}
plain('packages/hologpu/src/effects.ts', `export { catalogue } from '@mk7s/hologpu-effects';\n`);
await formatted(
  'packages/hologpu/src/effect-loaders.ts',
  `// Generated lazy effect resolver. No effect implementation loads until selected.
import type { EffectDefinition } from '@mk7s/hologpu-core';
const loaders: Record<string, () => Promise<{default: EffectDefinition}>> = {${ids.map((id) => `'${id}': () => import('@mk7s/hologpu-effects/${id}')`).join(',\n')}};
export async function loadEffect(id: string): Promise<EffectDefinition> { const load = loaders[id]; if (!load) throw new Error('Unknown effect: '+id); return (await load()).default; }
`,
);
plain('packages/hologpu/package.json', JSON.stringify(p, null, 2) + '\n');
plain('packages/effects/package.json', JSON.stringify(e, null, 2) + '\n');

// catalogue.json: one record per effect with a `status` derived from its tier (M3 3.9/3.10).
/** First real paragraph of an effect's research note, for the catalogue summary. */
const readSummary = (id) => {
  const file = `docs/notes/${id}.md`;
  if (!existsSync(file)) return '';
  const paragraph = [];
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const t = line.trim();
    if (!t) {
      if (paragraph.length) break;
      continue;
    }
    if (/^[#>|]|^- |^\d+\. /.test(t)) {
      if (paragraph.length) break;
      continue;
    }
    paragraph.push(t);
  }
  return paragraph
    .join(' ')
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1')
    .replace(/[`*_]/g, '')
    .trim();
};

// `docs/backlog-v2.md` §1.3 names the effects that should not run on a launch page.
const UNSUITABLE = new Set([
  'fluid-obstacles',
  'fluid',
  'flow-particles',
  'radiance-cascades',
  'lenia',
  'reaction-diffusion',
  'life',
  'falling-sand',
  'physarum',
  'caustics',
  'attractors',
  'n-body',
  'boids',
  'sort',
  'spatial-hash',
]);
const statusOf = (id, tier, hasPoster) =>
  UNSUITABLE.has(id)
    ? 'research'
    : tier !== 'T1'
      ? tier === 'T2'
        ? 'demo'
        : 'research'
      : hasPoster
        ? 'ready'
        : 'demo';
const effects = [];
for (const id of ids) {
  const file = `packages/effects/src/${id}/index.ts`;
  const sf = ts.createSourceFile(file, readFileSync(file, 'utf8'), ts.ScriptTarget.Latest, true);
  const literal = (node) =>
    !node
      ? null
      : ts.isStringLiteral(node) || ts.isNoSubstitutionTemplateLiteral(node)
        ? node.text
        : ts.isNumericLiteral(node)
          ? Number(node.text)
          : ts.isArrayLiteralExpression(node)
            ? node.elements.map(literal)
            : ts.isObjectLiteralExpression(node)
              ? Object.fromEntries(
                  node.properties
                    .filter(ts.isPropertyAssignment)
                    .map((prop) => [
                      prop.name.getText(sf).replace(/['"]/g, ''),
                      literal(prop.initializer),
                    ]),
                )
              : null;
  let meta;
  const visit = (node) => {
    if (ts.isObjectLiteralExpression(node)) {
      const fields = Object.fromEntries(
        node.properties
          .filter(ts.isPropertyAssignment)
          .map((prop) => [prop.name.getText(sf).replace(/['"]/g, ''), literal(prop.initializer)]),
      );
      if (fields.id === id && fields.title) meta = fields;
    }
    ts.forEachChild(node, visit);
  };
  visit(sf);
  const poster = ['poster.png', 'poster.webp']
    .map((f) => `packages/effects/src/${id}/${f}`)
    .find(existsSync);
  effects.push({
    id,
    title: meta?.title ?? id,
    summary: readSummary(id),
    family: meta?.family ?? 'procedural',
    tier: meta?.tier ?? 'T1',
    tags: meta?.tags ?? [],
    status: statusOf(id, meta?.tier ?? 'T1', Boolean(poster)),
    poster: poster ?? null,
    // Facets for the site's filters (M5 story 5.9).
    needsPointer: (meta?.inputs ?? []).includes('pointer'),
    behindDom: (meta?.tags ?? []).some((tag) => tag === 'overlay' || tag.startsWith('dom')),
    reducedMotionSafe: (meta?.reducedMotion?.time ?? 0) === 0,
  });
}
effects.sort((a, b) => a.title.localeCompare(b.title));
plain('catalogue.json', JSON.stringify({ project: 'hologpu', effects }, null, 2) + '\n');

if (check) {
  const stale = [];
  for (const [path, content] of outputs) {
    const current = existsSync(path) ? readFileSync(path, 'utf8') : null;
    if (current !== content) stale.push(path);
  }
  if (stale.length) {
    console.error(
      `Generated output is stale (run \`pnpm catalogue\`):\n${stale.map((s) => `  ${s}`).join('\n')}`,
    );
    process.exit(1);
  }
  console.log(`Generated output is up to date (${outputs.size} files, ${ids.length} effects).`);
} else {
  for (const [path, content] of outputs) await writeFile(path, content);
  console.log(
    `Wrote ${outputs.size} files for ${ids.length} effects (${effects.filter((e) => e.status === 'ready').length} ready).`,
  );
}
