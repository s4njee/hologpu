#!/usr/bin/env node
// MAINTAINER-ONLY: builds HoloGPU under /hologpu/ and stages it in the maintainer's
// personal mk7s Cloudflare Pages site. It expects a sibling `mk7s` checkout and is not
// part of the public build, test or release path. `pnpm publish:mk7s` runs it.
// Build HoloGPU under /hologpu/ and stage it in mk7s's Cloudflare Pages site.
import { spawnSync } from 'node:child_process';
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  readdirSync,
  rmSync,
  writeFileSync,
} from 'node:fs';
import path from 'node:path';
import { parseArgs } from 'node:util';

const { values } = parseArgs({
  options: {
    mk7s: { type: 'string' },
    deploy: { type: 'boolean', default: false },
    branch: { type: 'string', default: 'main' },
  },
});
const root = path.resolve(import.meta.dirname, '..');
const mk7s = path.resolve(root, values.mk7s ?? '../../mk7s');
const output = path.join(root, 'artifacts/mk7s');
const target = path.join(mk7s, 'public/hologpu');
if (
  !existsSync(path.join(mk7s, 'package.json')) ||
  JSON.parse(readFileSync(path.join(mk7s, 'package.json'), 'utf8')).name !== 'mk7s'
) {
  throw new Error(`Expected the mk7s site at ${mk7s}`);
}
function run(command, args, cwd) {
  const result = spawnSync(command, args, { cwd, stdio: 'inherit' });
  if (result.status !== 0) throw new Error(`${command} failed with status ${result.status}`);
}
run(
  'pnpm',
  ['exec', 'vite', 'build', '--base', '/hologpu/', '--outDir', output, '--emptyOutDir'],
  path.join(root, 'apps/playground'),
);
if (!existsSync(path.join(output, 'lcd.html'))) throw new Error('LCD demo build is missing');
if (!existsSync(path.join(output, 'fluid-dom.html')))
  throw new Error('DOM fluid demo build is missing');
if (!existsSync(path.join(output, 'noir.html'))) throw new Error('Noir demo build is missing');
for (const page of ['launch.html', 'device-check.html', 'fireworks-dom.html']) {
  if (!existsSync(path.join(output, page)))
    throw new Error(`Required demo build is missing: ${page}`);
}
// Plain HTML anchors are not rewritten by Vite's base option.
for (const file of readdirSync(output).filter((file) => file.endsWith('.html'))) {
  const source = path.join(output, file);
  writeFileSync(
    source,
    readFileSync(source, 'utf8').replace(/\b(href|src)="\/(?!\/|hologpu\/)/g, '$1="/hologpu/'),
  );
}
mkdirSync(path.dirname(target), { recursive: true });
rmSync(target, { recursive: true, force: true });
cpSync(output, target, { recursive: true });
const headersPath = path.join(mk7s, 'public/_headers');
const begin = '# BEGIN hologpu (generated by hologpu/scripts/publish-site-mk7s.mjs)';
const end = '# END hologpu';
let headers = existsSync(headersPath) ? readFileSync(headersPath, 'utf8') : '';
const first = headers.indexOf(begin),
  last = headers.indexOf(end);
if (first >= 0 && last > first)
  headers = headers.slice(0, first) + headers.slice(last + end.length);
const block = `${begin}\n/hologpu/*\n  Cache-Control: public, max-age=0, must-revalidate\n  X-Content-Type-Options: nosniff\n/hologpu/assets/*\n  ! Cache-Control\n  Cache-Control: public, max-age=31536000, immutable\n${end}`;
writeFileSync(headersPath, `${headers.trim()}\n\n${block}\n`);
const redirectsPath = path.join(mk7s, 'public/_redirects');
const redirects = existsSync(redirectsPath) ? readFileSync(redirectsPath, 'utf8') : '';
if (!redirects.split('\n').includes('/hologpu /hologpu/ 308'))
  writeFileSync(redirectsPath, `${redirects.trimEnd()}\n/hologpu /hologpu/ 308\n`);
console.log(`Staged ${target}; noir demo: /hologpu/noir.html`);
if (values.deploy) {
  run('npm', ['run', 'build'], mk7s);
  run(
    'npx',
    ['wrangler', 'pages', 'deploy', 'dist', '--project-name', 'mk7s', '--branch', values.branch],
    mk7s,
  );
}
